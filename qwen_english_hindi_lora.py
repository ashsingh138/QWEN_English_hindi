predictions = []
references = []
english_sentences = []

for example in val_dataset:

    en = example["translation"]["en"]
    hi = example["translation"]["hi"]

    messages = [
        {
            "role": "user",
            "content": f"Translate the following English sentence to Hindi:\n{en}"
        }
    ]

    text = tokenizer.apply_chat_template(
        messages,
        tokenize = False,
        add_generation_prompt = True
    )

    inputs = tokenizer(
        text,
        return_tensors = "pt"
    ).to("cuda")

    outputs = model.generate(
        **inputs,
        max_new_tokens = 128,
        do_sample = False,
        eos_token_id = tokenizer.eos_token_id,
    )

    decoded = tokenizer.decode(
        outputs[0],
        skip_special_tokens = True
    )

    prediction = decoded[len(text):].strip()

    english_sentences.append(en)
    references.append(hi)
    predictions.append(prediction)

print("Prediction generation complete!")

from evaluate import load


bleu = load("bleu")

bleu_score = bleu.compute(
    predictions = predictions,
    references = [[ref] for ref in references]
)


rouge = load("rouge")

rouge_score = rouge.compute(
    predictions = predictions,
    references = references
)


bertscore = load("bertscore")

bert_score = bertscore.compute(
    predictions = predictions,
    references = references,
    lang = "hi"
)



print("\nBLEU Score:")
print(bleu_score["bleu"])

print("\nROUGE Scores:")
print(rouge_score)

print("\nBERTScore F1 Average:")
print(sum(bert_score["f1"]) / len(bert_score["f1"]))

